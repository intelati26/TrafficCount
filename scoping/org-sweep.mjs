// For each state: take the official-looking owner accounts found by discover.mjs, resolve their ArcGIS Online organisation,
// search that org for traffic/road-inventory/crash content, and list any DOT-run ArcGIS servers (non arcgis.com hosts) with
// their folders/services. This is how ARDOT's own server (gis.ardot.gov) was found. Output: scoping/ORG_SOURCES.md / .json
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = dirname(fileURLToPath(import.meta.url));
const disc = JSON.parse(readFileSync(join(dir, 'discovered.json'), 'utf8'));
const J = async (u) => { for (let i = 0; i < 3; i++) { try { const r = await fetch(u, { signal: AbortSignal.timeout(30000), headers: { 'user-agent': 'traffic-archive-scoping/0.1' } }); return await r.json(); } catch { await new Promise(r => setTimeout(r, 700)); } } return null; };
const dotOwner = /dot|kytc|tpp_traf|\bmdt\b|trafficsurvey|dotd|udot|wvdot|ardot|oklahoma/i;
const want = /(aadt|\badt\b|traffic|volume|count|inventory|hpms|crash|safety|lane|road|highway|functional|pavement|congestion)/i;
const skip = /(job \d|vpi|survey123|_form|hub site|storymap|webmap|web map|_wfl1|\bpi\b|meeting|public comment)/i;
const serverRoot = (url) => { const m = /^(https?:\/\/[^/]+\/.*?\/rest\/services)/i.exec(url); return m ? m[1] : null; };

async function sweep(r) {
  const owners = [...new Set(r.probed.filter(p => p.layers.length && dotOwner.test(p.owner)).map(p => p.owner))].slice(0, 2);
  const out = { state: r.state, owners, org: null, items: [], servers: [] };
  let orgId = null;
  for (const o of owners) { const d = await J(`https://www.arcgis.com/sharing/rest/search?${new URLSearchParams({ q: `owner:"${o}"`, num: '1', f: 'json' })}`); orgId = d?.results?.[0]?.orgId; if (orgId) break; }
  if (!orgId) return out;
  out.org = orgId;
  const items = new Map();
  for (const q of [`orgid:${orgId} AND (AADT OR ADT OR "traffic count" OR "traffic volume" OR "road inventory" OR HPMS OR crash OR "functional class")`, `orgid:${orgId} AND (type:"Feature Service" OR type:"Map Service") AND (traffic OR road OR highway)`]) {
    const d = await J(`https://www.arcgis.com/sharing/rest/search?${new URLSearchParams({ q, num: '40', sortField: 'numviews', sortOrder: 'desc', f: 'json' })}`);
    for (const it of d?.results ?? []) if (it.url && /(Feature|Map) Service/.test(it.type) && want.test(it.title) && !skip.test(it.title)) items.set(it.url, { title: it.title, url: it.url, owner: it.owner.split('@')[0], views: it.numViews });
  }
  out.items = [...items.values()].slice(0, 12);
  const roots = new Set(out.items.map(i => serverRoot(i.url)).filter(u => u && !/arcgis\.com/i.test(u)));
  for (const root of roots) {
    const top = await J(`${root}?f=json`); if (!top) continue;
    const names = [];
    for (const s of top.services ?? []) names.push(s.name);
    for (const f of (top.folders ?? []).filter(f => !/^(Utilities|System|Hosted)$/i.test(f)).slice(0, 40)) { const d = await J(`${root}/${f}?f=json`); for (const s of d?.services ?? []) names.push(s.name); }
    out.servers.push({ root, folders: top.folders?.length ?? 0, matches: [...new Set(names.filter(n => want.test(n)).map(n => n.replace(/:.*/, '')))].slice(0, 25), services: names.length });
  }
  return out;
}

const res = [];
const list = disc.filter(r => r.probed.some(p => p.layers.length && dotOwner.test(p.owner)));
for (let i = 0; i < list.length; i += 4) res.push(...await Promise.all(list.slice(i, i + 4).map(sweep)));
writeFileSync(join(dir, 'org-sweep.json'), JSON.stringify(res, null, 1));
let md = `# DOT organisations and servers (sweep)\n\nFor states with an official-looking owner account: items in that org matching traffic/inventory/crash terms, and any DOT-run ArcGIS servers found (folders and matching services). Generated by scoping/org-sweep.mjs.\n\n`;
for (const r of res) {
  md += `## ${r.state}  (${r.owners.join(', ') || 'no owner'}${r.org ? `, org ${r.org}` : ''})\n`;
  for (const s of r.servers) md += `- **Server** ${s.root}: ${s.services} services in ${s.folders} folders. Matching: ${s.matches.join(', ') || 'none'}\n`;
  for (const i of r.items) md += `- ${i.title} — ${i.url} (${i.owner})\n`;
  md += '\n';
}
writeFileSync(join(dir, 'ORG_SOURCES.md'), md);
console.log(`${res.length} states swept; with own servers: ${res.filter(r => r.servers.length).length}`);
for (const r of res) console.log(r.state, r.items.length, r.servers.map(s => new URL(s.root).host + `(${s.matches.length})`).join(' '));
